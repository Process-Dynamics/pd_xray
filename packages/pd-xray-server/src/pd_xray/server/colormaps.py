def _imagej_interpolate(channels: tuple[str, ...]) -> NDArray[np.uint8]:
    """ImageJ's LutLoader.interpolate: linear interpolation of n control points to 256 entries, truncated."""
    points = [np.array(channel.split(), dtype=float) for channel in channels]
    n = len(points[0])
    position = np.arange(256) * (n / 256)
    low = position.astype(int)
    high = np.minimum(low + 1, n - 1)
    fraction = position - low
    table: NDArray[np.uint8] = np.stack([(1 - fraction) * p[low] + fraction * p[high] for p in points], axis=1)
    return table.astype(np.uint8)


def _tables() -> dict[str, NDArray[np.uint8]]:
    grey = np.repeat(np.arange(256, dtype=np.uint8)[:, None], 3, axis=1)
    tables = {"grey": grey, "grey_inverted": grey[::-1].copy()}
    tables.update(
        {name: np.frombuffer(bytes.fromhex("".join(text)), np.uint8).reshape(256, 3) for name, text in _HEX.items()}
    )
    tables["fire"] = _imagej_interpolate(_FIRE)
    for table in tables.values():
        table.flags.writeable = False
    return tables


COLORMAPS: Mapping[str, NDArray[np.uint8]] = MappingProxyType(_tables())
"""Colour map name -> read-only (256, 3) uint8 RGB table. "grey" leaves images single-channel."""
